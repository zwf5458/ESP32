#pragma once
#include <Arduino.h>
#include <Wire.h>

// SSD1306 128x64 极简轻量级 I2C 驱动 (无任何第三方库依赖，纯基于 Wire.h)
// 内存占用: 1024 字节帧缓冲; 纯静态内嵌 5x7 ASCII 字模 (475 字节)
class TinySSD1306 {
public:
  static const uint8_t I2C_ADDR = 0x3C;
  uint8_t buffer[1024];

  bool begin(int sda = 4, int scl = 5) {
    Wire.begin(sda, scl);
    Wire.setClock(400000);
    Wire.beginTransmission(I2C_ADDR);
    if (Wire.endTransmission() != 0) {
      // 备用地址 0x3D 探测
      Wire.beginTransmission(0x3D);
      if (Wire.endTransmission() != 0) return false;
      mAddr = 0x3D;
    } else {
      mAddr = 0x3C;
    }

    static const uint8_t initSeq[] = {
      0xAE,       // 关闭显示
      0xD5, 0x80, // 设置时钟分频
      0xA8, 0x3F, // 多路复用 64
      0xD3, 0x00, // 显示偏移 0
      0x40,       // 起始行 0
      0x8D, 0x14, // 开启内置电荷泵升压 (必须开启, 否则屏幕不发光)
      0x20, 0x00, // 页水平寻址模式
      0xA1,       // 段重映射 (左右反转适配标准排针方向)
      0xC8,       // COM 扫描方向 (上下反转)
      0xDA, 0x12, // COM 硬件引脚配置
      0x81, 0xCF, // 对比度亮度 0xCF
      0xD9, 0xF1, // 预充电周期
      0xDB, 0x40, // VCOMH 判定电平
      0xA4,       // 恢复正常 RAM 显示
      0xA6,       // 正显 (非反相)
      0xAF        // 打开显示
    };
    for (size_t i = 0; i < sizeof(initSeq); i++) {
      sendCmd(initSeq[i]);
    }
    clear();
    display();
    return true;
  }

  void clear() {
    memset(buffer, 0, sizeof(buffer));
  }

  // 在 (x, y) 处绘制单个像素
  void drawPixel(int16_t x, int16_t y, uint8_t color = 1) {
    if (x < 0 || x >= 128 || y < 0 || y >= 64) return;
    if (color) {
      buffer[x + (y / 8) * 128] |= (1 << (y & 7));
    } else {
      buffer[x + (y / 8) * 128] &= ~(1 << (y & 7));
    }
  }

  // 绘制 5x7 ASCII 字符 (scale=1 为 6x8 像素, scale=2 为 12x16 像素大字体)
  void drawChar(int16_t x, int16_t y, char c, uint8_t scale = 1) {
    if (c < 32 || c > 126) c = '?';
    const uint8_t *glyph = &FONT_5x7[(c - 32) * 5];
    for (uint8_t col = 0; col < 5; col++) {
      uint8_t line = glyph[col];
      for (uint8_t row = 0; row < 7; row++) {
        if (line & 1) {
          if (scale == 1) {
            drawPixel(x + col, y + row, 1);
          } else {
            for (uint8_t sx = 0; sx < scale; sx++) {
              for (uint8_t sy = 0; sy < scale; sy++) {
                drawPixel(x + col * scale + sx, y + row * scale + sy, 1);
              }
            }
          }
        }
        line >>= 1;
      }
    }
  }

  // 绘制单行文本
  void drawString(int16_t x, int16_t y, const char *str, uint8_t scale = 1) {
    int16_t curX = x;
    while (*str) {
      if (curX + 6 * scale > 128) break; // 超出右边界截断
      drawChar(curX, y, *str, scale);
      curX += 6 * scale;
      str++;
    }
  }

  // 发送显存缓冲到屏幕
  void display() {
    for (uint8_t page = 0; page < 8; page++) {
      sendCmd(0xB0 + page); // 设置页地址
      sendCmd(0x00);        // 设置列低地址
      sendCmd(0x10);        // 设置列高地址
      for (uint8_t chunk = 0; chunk < 128; chunk += 16) {
        Wire.beginTransmission(mAddr);
        Wire.write(0x40);   // 数据前缀
        Wire.write(&buffer[page * 128 + chunk], 16);
        Wire.endTransmission();
      }
    }
  }

private:
  uint8_t mAddr = I2C_ADDR;

  void sendCmd(uint8_t cmd) {
    Wire.beginTransmission(mAddr);
    Wire.write(0x00); // 命令前缀
    Wire.write(cmd);
    Wire.endTransmission();
  }

  // 标准 5x7 ASCII 字符集 (ASCII 32 ' ' 到 126 '~')
  static const uint8_t FONT_5x7[475];
};

